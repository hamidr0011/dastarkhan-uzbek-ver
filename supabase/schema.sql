create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text unique not null,
  phone text,
  role text not null default 'customer' check (role in ('customer', 'manager')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
on public.profiles for select
using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own"
on public.profiles for insert
with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text unique not null,
  customer_id uuid not null references auth.users(id) on delete cascade,
  customer_name text,
  items jsonb not null,
  subtotal numeric(10, 2) not null default 0,
  tax numeric(10, 2) not null default 0,
  total numeric(10, 2) not null,
  currency text not null default 'UZS',
  status text not null default 'Placed',
  order_type text not null check (order_type in ('Dine In', 'Takeaway')),
  table_number integer,
  guest_count integer,
  pickup_name text,
  pickup_time text,
  payment_method text,
  payment_status text,
  payment_reference text,
  special_request text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.orders enable row level security;

drop policy if exists "orders_select_own_or_manager" on public.orders;
create policy "orders_select_own_or_manager"
on public.orders for select
using (
  auth.uid() = customer_id
  or exists (select 1 from public.profiles where id = auth.uid() and role = 'manager')
);

drop policy if exists "orders_insert_own" on public.orders;
create policy "orders_insert_own"
on public.orders for insert
with check (auth.uid() = customer_id);

drop policy if exists "orders_update_own_or_manager" on public.orders;
create policy "orders_update_own_or_manager"
on public.orders for update
using (
  auth.uid() = customer_id
  or exists (select 1 from public.profiles where id = auth.uid() and role = 'manager')
);

