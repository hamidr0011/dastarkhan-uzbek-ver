create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(10, 2) not null,
  category text not null,
  image text,
  available boolean not null default true,
  is_special boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.menu_items enable row level security;

drop policy if exists "menu_public_read" on public.menu_items;
create policy "menu_public_read"
on public.menu_items for select
using (true);

drop policy if exists "menu_manager_write" on public.menu_items;
create policy "menu_manager_write"
on public.menu_items for all
using (exists (select 1 from public.profiles where id = auth.uid() and role = 'manager'))
with check (exists (select 1 from public.profiles where id = auth.uid() and role = 'manager'));

